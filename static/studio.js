function cancelStudio(message = true) {
  const state = studioState();
  state.revision++;
  state.requests.forEach((controller) => controller.abort());
  state.requests.clear();
  if (message) {
    state.status = t("reviewCanceled");
    state.error = false;
  }
}
function resetStudio(preserveUndo = false) {
  const state = studioState(),
    wasOpen = state.open,
    previous = state.previous;
  cancelStudio(false);
  Object.assign(state, {
    analysis: null,
    comparison: null,
    otherText: "",
    audit: null,
    previous: preserveUndo ? previous : null,
    status: "",
    error: false,
    open: preserveUndo && wasOpen,
  });
}
function requestOwnsStudio(workspace, epoch, revision, action, controller) {
  return (
    activeFeature() === workspace &&
    modeEpoch === epoch &&
    workspace.studio.revision === revision &&
    workspace.studio.requests.get(action) === controller
  );
}
async function reviewAction(action) {
  if (!canAnalyze()) return;
  const workspace = activeFeature(),
    state = studioState(),
    epoch = modeEpoch,
    revision = state.revision,
    snapshot = { ...currentTranslation },
    controller = new AbortController();
  const other = state.otherText.trim();
  if (action === "compare" && !other) return;
  state.requests.get(action)?.abort();
  state.requests.set(action, controller);
  state.open = true;
  state.error = false;
  state.status = t(action === "analyze" ? "reviewWorking" : "compareWorking");
  renderStudio();
  try {
    const data = await responseJson(
      await fetch(`/api/${action}`, {
        method: "POST",
        signal: controller.signal,
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          ...studioPayload(snapshot),
          ...(action === "compare" ? { other_translation: other } : {}),
        }),
      })
    );
    if (!requestOwnsStudio(workspace, epoch, revision, action, controller)) return;
    if (action === "analyze") {
      state.analysis = data;
      state.audit = data.audit;
    } else state.comparison = data;
    state.status = "";
  } catch (error) {
    if (
      error.name !== "AbortError" &&
      requestOwnsStudio(workspace, epoch, revision, action, controller)
    ) {
      state.status = error.message || t("failed");
      state.error = true;
    }
  } finally {
    if (requestOwnsStudio(workspace, epoch, revision, action, controller)) {
      state.requests.delete(action);
      renderStudio();
    }
  }
}
async function applyStudioWording(translation, undo = false) {
  if (!currentTranslation || studioState().requests.size) return;
  const workspace = activeFeature(),
    state = studioState(),
    epoch = modeEpoch,
    revision = state.revision,
    original = { ...currentTranslation },
    controller = new AbortController();
  state.requests.set("apply", controller);
  state.status = t("auditWorking");
  renderStudio();
  try {
    const data = await responseJson(
      await fetch("/api/audit", {
        method: "POST",
        signal: controller.signal,
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ ...studioPayload(original), translation }),
      })
    );
    if (!requestOwnsStudio(workspace, epoch, revision, "apply", controller)) return;
    state.previous = undo ? null : original;
    state.requests.delete("apply");
    applyingStudioWording = true;
    try {
      commitTranslation({ ...original, translation, audit: data.audit });
    } finally {
      applyingStudioWording = false;
    }
    state.open = true;
    renderStudio();
  } catch (error) {
    if (
      error.name !== "AbortError" &&
      requestOwnsStudio(workspace, epoch, revision, "apply", controller)
    ) {
      state.status = error.message;
      state.error = true;
    }
  } finally {
    if (requestOwnsStudio(workspace, epoch, revision, "apply", controller)) {
      state.requests.delete("apply");
      renderStudio();
    }
  }
}
function wordingButton(text, translation) {
  const button = studioNode("button", text, "outline-button");
  button.type = "button";
  button.disabled = studioState().requests.size > 0;
  button.addEventListener("click", () => applyStudioWording(translation));
  return button;
}
