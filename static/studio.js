$("studio-export").addEventListener("click", () => {
  if (!currentTranslation) return;
  const state = studioState(),
    report = {
      version: 1,
      exported_at: new Date().toISOString(),
      review_type: "AI-assisted review, not an independently certified benchmark",
      source: currentTranslation.text,
      translation: currentTranslation.translation,
      source_language: effectiveSource(),
      target_language: currentTranslation.target,
      tone: currentTranslation.tone,
      context: currentTranslation.context || "general",
      extra_context: currentTranslation.extra_context || "",
      terminology: currentTranslation.glossary || [],
      other_translation: state.otherText,
      analysis: state.analysis,
      comparison: state.comparison,
      consistency_checks: state.audit,
    };
  const url = URL.createObjectURL(
    new Blob([JSON.stringify(report, null, 2)], { type: "application/json;charset=utf-8" })
  );
  const link = document.createElement("a");
  link.href = url;
  link.download = "translation-review.json";
  document.body.append(link);
  link.click();
  link.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
});
