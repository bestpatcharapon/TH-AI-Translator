function validLocalGlossary(terms) {
  if (!Array.isArray(terms) || terms.length > 30) return false;
  const seen = new Set();
  return terms.every((entry) => {
    if (
      !entry ||
      typeof entry.source !== "string" ||
      typeof entry.target !== "string" ||
      !entry.source.trim() ||
      !entry.target.trim() ||
      entry.source.length > 120 ||
      entry.target.length > 120 ||
      /[\u0000-\u001f]/.test(entry.source + entry.target) ||
      !LANGUAGE_CATALOG[entry.language]
    )
      return false;
    const key = JSON.stringify([entry.source.trim().toLocaleLowerCase(), entry.language]);
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });
}
